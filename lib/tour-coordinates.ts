const PHOTO_BY_FILE = new Map<string, GpsPhoto>(
  FIELD_PHOTOS.filter((p) => p.hasExif && p.src).map((p) => [p.file, p]),
)

export const LOCATED_POINTS: LocatedPoint[] = ROWS.map(([file, lat, lng, takenAt]) => {
  const photo = PHOTO_BY_FILE.get(file)
  return {
    file,
    lat,
    lng,
    takenAt,
    src: photo?.src,
    caption: photo?.caption,
  }
})

export const PHOTO_POINTS = LOCATED_POINTS.filter((p) => p.src)
export const COORD_ONLY_POINTS = LOCATED_POINTS.filter((p) => !p.src)

/* Parse "2014:07:16 20:35:59" → hour as a number (0-23) for time-of-day tinting. */
export function hourOf(takenAt: string): number {
  const m = takenAt.match(/\s(\d{2}):/)
  return m ? Number.parseInt(m[1], 10) : 12
}

/* "2014:07:16 20:35:59" → "2014-07-16 · 20:35" */
export function formatStamp(takenAt: string): string {
  const m = takenAt.match(/^(\d{4}):(\d{2}):(\d{2})\s+(\d{2}):(\d{2})/)
  if (!m) return takenAt
  const [, y, mo, d, h, mi] = m
  return `${y}-${mo}-${d} · ${h}:${mi}`
}
